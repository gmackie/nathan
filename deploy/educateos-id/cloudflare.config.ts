// Staging-only deployment of Nathan's private application entrypoints and Access-protected management.
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";
import { stripJsonc } from "../../scripts/lib/wrangler.mjs";

export const workerName = "nathan-educateos-stg-auth";
export const applicationOrigin = "https://staging.educateos.io";
export const webClientId = "educateos-web-staging";
const target = new URL("./wrangler.auth.jsonc", import.meta.url);

/** Keep the runtime, build, Durable Object migration and compatibility flags from the Nathan release. */
export async function configuration() {
  const base = JSON.parse(stripJsonc(await readFile(new URL("../../wrangler.auth.jsonc", import.meta.url), "utf8")));
  return {
    $schema: "../../node_modules/wrangler/config-schema.json",
    name: workerName,
    account_id: "c07a7e704db1808e1fff91bed2b1cd49",
    main: "../../" + base.main,
    compatibility_date: base.compatibility_date,
    compatibility_flags: base.compatibility_flags,
    workers_dev: false,
    preview_urls: false,
    routes: [],
    observability: { enabled: true, logs: { invocation_logs: false } },
    build: base.build,
    durable_objects: base.durable_objects,
    migrations: base.migrations,
    triggers: { crons: ["* * * * *", "12 5 * * *"] },
    d1_databases: [{
      binding: "DB", database_name: workerName, database_id: "219478ac-318b-4af7-84d0-c8b83ebd7d70",
      migrations_dir: "../../migrations",
    }],
    send_email: [{ name: "SEND_EMAIL", allowed_sender_addresses: ["sign-in@mail.staging.educateos.io"] }],
    vars: {
      NATHAN_ISSUER: "https://id-stg.educateos.io",
      NATHAN_APP_ORIGIN: applicationOrigin,
      NATHAN_APP_ID: "educateos",
      NATHAN_ACCESS_TEAM_DOMAIN: "gmacko.cloudflareaccess.com",
      NATHAN_ACCESS_AUD: "794aa43e2e61b79b8dadef328f13e584717d032bc232dc76dd01a379f5a48685",
      NATHAN_INSTANCE_NAME: "EducateOS",
      NATHAN_SECURITY_PROFILE: "business",
      NATHAN_BOOTSTRAP_REQUIRED: "true",
      NATHAN_ADMIN_STEPUP_REQUIRED: "true",
      NATHAN_INSTALL_ACTIVE: "true",
      NATHAN_MCP_WRITE_ENABLED: "false",
      ENABLE_PASSWORD: "true",
      ENABLE_EMAIL_OTP: "true",
      ENTERPRISE_SSO: "false",
    },
  };
}

export async function renderConfig() {
  return "// Generated by deploy/educateos-id/cloudflare.config.ts\n" + JSON.stringify(await configuration(), null, 2) + "\n";
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const content = await renderConfig();
  if (process.argv.length === 2) await writeFile(target, content);
  else if (process.argv.length === 3 && process.argv[2] === "--check") {
    if (content !== await readFile(target, "utf8")) throw Error("Regenerate the EducateOS staging Worker configuration");
  } else throw Error("Expected no arguments, or --check");
}
